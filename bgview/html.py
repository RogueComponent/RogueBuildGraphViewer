def to_html(graph: Graph, findings: list[Finding], ev: EvalResult, path: str) -> None:
    """Render the report and write it to `path`.

    Thin wrapper over `render_html` -- V38: `--serve` and `--html` must go
    through one renderer, so a finding shown in the live picker is byte for
    byte the finding in the written file."""
    out_path = pathlib.Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_html(graph, findings, ev), encoding="utf-8")


def render_html(graph: Graph, findings: list[Finding], ev: EvalResult) -> str:
    """Render the self-contained HTML report (T13) and return it as a string.

    Pure rendering: every finding, edge, and condition verdict shown here
    already exists in `graph`/`findings`/`ev` -- nothing is re-detected or
    re-classified. See the module docstring for the security posture
    (V8/V17) this function's structure is built around."""
    edges = _build_edges(graph)
    node_id_by_name = {name: f"n{i}" for i, name in enumerate(graph.nodes)}

    node_by_loc = _node_by_loc(graph)
    agent_by_loc = _agent_by_loc(ev)
    verdicts = _d12_verdicts(findings)

    targets = [_finding_target(f, graph, node_by_loc, agent_by_loc) for f in findings]
    # Resolved BEFORE layout: a warn badge reserves width inside its own box,
    # so which nodes carry one is an input to how wide they are drawn.
    warn_nodes = {t[1] for f, t in zip(findings, targets) if t and t[0] == "node" and f.severity >= Severity.WARN}

    lanes, node_pos, total_width = _assign_positions(graph, warn_nodes)
    lane_id_by_index = [f"l{i}" for i in range(len(lanes))]
    node_conditions, agent_conditions = _collect_conditions(ev, verdicts)

    # `_render_findings_panel` needs a stable ("node"|"agent", name) ->
    # synthetic-id-index mapping to emit each row's `data-target`.
    target_index: dict[tuple[str, str], int] = {("node", name): int(node_id_by_name[name][1:]) for name in graph.nodes}
    target_index.update({("agent", lanes[i]["name"]): i for i in range(len(lanes))})

    collapsed_default = len(graph.nodes) > _LARGE_NODE_THRESHOLD or len(lanes) > _LARGE_LANE_THRESHOLD

    source_files = _source_files(graph, ev)
    source_index = _source_index_by_file(source_files)
    source_marks = _source_marks(findings, source_index)

    def _src_of(file_path: str) -> int | None:
        """Index into `source_files` for a model/finding `file`, or None
        when that file's text was never captured -- a hand-built Graph, or
        a finding raised against a path this evaluation did not read. The
        JS treats None as "no source to jump to" and says so, rather than
        silently doing nothing on a double-click."""
        return source_index.get(os.path.normcase(os.path.normpath(file_path)))

    svg_markup, total_width, _total_height = _render_svg(
        graph, lanes, node_pos, edges, node_id_by_name, lane_id_by_index,
        warn_nodes, agent_conditions, collapsed_default, total_width,
    )

    script_name = _basename(_source_file(graph, ev)) or "(unknown script)"

    payload = {
        "nodes": [
            {
                "id": node_id_by_name[name],
                "name": name,
                "agent": node.agent,
                "file": node.file,
                "line": node.line,
                # Whole-element source range (V-less, purely presentational)
                # + which embedded file it lives in, so a double-click can
                # highlight `<Node ...>` through `</Node>` without the
                # renderer ever looking at the .xml again.
                "endLine": node.line_span[1],
                "src": _src_of(node.file),
                "lane": node_pos[name]["lane"],
                "col": node_pos[name]["col"],
                "row": node_pos[name]["row"],
                # Absolute local x and the box's own width, packed once in
                # _assign_positions. relayout() reads these instead of
                # re-deriving them from a column stride that no longer exists.
                "x": node_pos[name]["x"],
                "w": node_pos[name]["w"],
                "produces": sorted(node.produces),
                "consumes": sorted(node.consumes),
                # Tags this node's own tasks CREATE. Not shown as its own
                # inspector section (the node's declared surface is what a
                # reader wants there), but a lens asking "what produces this
                # tag" has to count them or it under-reports: a tag made by a
                # `<Tag With=...>` inside the node is produced there whether or
                # not it was hoisted into `@Produces`. That gap is D4's whole
                # subject, so a lens that ignored it would contradict a
                # detector shipped in the same report.
                "creates": sorted(node.creates),
                "requires": list(node.requires),
                "after": list(node.after),
                "conditions": node_conditions.get(name, []),
                "findingIds": [f"f{i}" for i, t in enumerate(targets) if t == ("node", name)],
            }
            for name, node in graph.nodes.items()
        ],
        "lanes": [
            {
                "id": lane_id_by_index[lane["index"]],
                "name": lane["name"],
                "rows": lane["rows"],
                "nodeCount": lane["node_count"],
                "collapsedDefault": collapsed_default,
                "conditions": agent_conditions.get(lane["name"], []),
            }
            for lane in lanes
        ],
        # NB "from"/"to" are synthetic node ids (matching each node's own
        # "id" field above and the static SVG's `data-from`/`data-to`
        # attributes) -- NOT raw node names. `_build_edges` returns names;
        # `relayout()`'s `nodesById[e.from]` lookup requires ids.
        "edges": [{"from": node_id_by_name[frm], "to": node_id_by_name[to], "kind": kind} for frm, to, kind in edges],
        "findings": [
            {
                "id": f"f{i}",
                "line": f.line,
                "severity": f.severity.name.lower(),
                "detector": f.detector,
                "message": f.message,
                "file": f.file,
                "src": _src_of(f.file),
                # The tag a finding is ABOUT, when it is about one (D2/D3/D4/
                # D5 all are). This is the most direct route into the lenses
                # there is: the findings panel is where a reader starts, and
                # "this warning names #BinaryFiles -- show me everything that
                # touches it" is one drag from the verdict.
                "tag": f.tag or "",
            }
            for i, f in enumerate(findings)
        ],
        "sources": [
            {"index": sf["index"], "path": sf["path"], "name": sf["name"], "lineCount": len(sf["lines"])}
            for sf in source_files
        ],
    }

    doc = "".join(
        [
            "<!DOCTYPE html>\n",
            '<html lang="en">\n<head>\n<meta charset="utf-8"/>\n',
            f"<title>{_esc(script_name)} — bgview report</title>\n",
            f"<style>{_CSS}</style>\n</head>\n<body>\n",
            _render_header(script_name, len(graph.nodes), len(graph.agents), _distinct_tag_count(graph)),
            '<div id="layout">\n',
            _render_findings_panel(findings, targets, target_index),
            _render_resizer("findings", "Resize the findings panel"),
            '<div id="center-pane">\n',
            _render_tabstrip(source_files),
            # tabindex="-1": focusable by CLICK (so Home reaches the canvas's
            # own keydown handler) without inserting the whole canvas into the
            # tab order ahead of the node boxes, which are already reachable.
            '<main id="graph-area" role="tabpanel" aria-labelledby="tab-btn-graph" aria-label="Graph" tabindex="-1">\n',
            svg_markup,
            "\n</main>\n",
            _render_source_area(source_files, source_marks),
            "</div>\n",
            _render_resizer("inspector", "Resize the details panel"),
            _render_inspector_skeleton(),
            "</div>\n",
            f'<script type="application/json" id="bgview-data">{_json_script_safe(payload)}</script>\n',
            _render_script(total_width),
            "\n</body>\n</html>\n",
        ]
    )

    return doc


def _source_file(graph: Graph, ev: EvalResult) -> str:
    for node in graph.nodes.values():
        if node.file:
            return node.file
    for r in ev.resolved:
        if r.elem.file:
            return r.elem.file
    return ""


def _distinct_tag_count(graph: Graph) -> int:
    tags: set[str] = set()
    for node in graph.nodes.values():
        for t in node.produces | node.creates | node.consumes:
            tags.add(t.lower())
    return len(tags)
