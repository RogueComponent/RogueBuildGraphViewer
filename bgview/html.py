# geometry constants -- shared, by construction, between the Python initial
# render (always computed as if every lane were expanded) and the mirrored
# arithmetic in the inline JS (which is what actually applies the collapsed
# state, including on first paint -- see _JS_TEMPLATE's relayout()). Both
# sides read these SAME numbers: Python uses them directly; the JS copy is
# produced by substituting these exact values into _JS_TEMPLATE's
# `__TOKEN__` placeholders, so the two can never drift apart.
# ---------------------------------------------------------------------------
_MARGIN_X = 24
_MARGIN_TOP = 20
_ROW_H = 66
_NODE_H = 34
_LANE_HEADER_H = 34
_LANE_PAD = 22

# Node boxes are sized to their own label, and columns are packed to the
# widest box in them, rather than everything sharing one fixed width. Node
# names in real scripts run from "Compile" to
# "Compile $(EditorTarget) $(TargetPlatform) $(Configuration)" -- one width
# for both means either a wall of half-empty boxes or a wall of truncated
# ones, and a truncated node name is not identifying information.
#
# The label font is `var(--font-data)`, whose fallback chain ends in
# `monospace`, so every glyph advances the same width and the label's width
# is knowable from its length alone -- no font metrics, no measuring pass, no
# layout jump after paint. Real monospace faces advance between ~0.5em and
# ~0.62em; taking the TOP of that range means the estimate errs toward a
# slightly roomy box rather than a clipped one, on every face.
_NODE_FONT_PX = 11
_NODE_CHAR_W = _NODE_FONT_PX * 0.62
_NODE_PAD_X = 9                 # left inset of the label, mirrored on the right
_NODE_BADGE_W = 18              # room the warn badge needs in the top-right
_NODE_MIN_W = 96
# How far, in rows, a wire corridor has to stay from a box's row before the
# box actually has to move. A box occupies only `_NODE_H` of the `_ROW_H`
# row pitch and a wire enters/leaves at the box's vertical centre, so a wire
# clears a box once it is more than half a box height away -- 17 of 66 rows,
# about 0.26. Demanding a full row of separation (the obvious guess) reserves
# nearly four times the space actually needed and shoves boxes into the next
# band for no visual gain. The extra 6px is breathing room so a wire does not
# graze a border.
_WIRE_CLEARANCE = (_NODE_H / 2 + 6) / _ROW_H
# A ceiling only a pathological name reaches. Past it the label is clipped --
# with the whole name still in the box's <title> and in the inspector.
_NODE_MAX_W = 460
_COL_GAP = 116                  # horizontal room for the connection splines

# §T13: "usable from ~10 nodes up to thousands" -- stay expanded through a
# normal-sized graph, auto-collapse once it would otherwise become a
# hairball on first paint. Applied uniformly (not per-lane): either the
# whole graph is small enough to show open, or every lane starts collapsed.
_LARGE_NODE_THRESHOLD = 40
_LARGE_LANE_THRESHOLD = 12

# Source-tab embedding caps. V17 says the report is ONE self-contained file;
# that is only a virtue while the file stays openable. A BuildGraph script
# is normally a few hundred lines, but `<Include>` chains reach across a
# whole studio's build repo, and one pathological (or adversarial -- V8:
# this input is another team's file) script must not turn the report into a
# hundred-megabyte document the browser cannot lay out. Over the cap the
# file's text is TRUNCATED and says so, visibly, in the source view itself
# -- never silently, and never by dropping the file from the picker (a
# missing file reads as "no such source"; a truncated one reads as what it
# is). Chosen an order of magnitude above the largest file in Epic's own
# corpus, so no real script is ever affected.
_MAX_SOURCE_LINES = 20_000
_MAX_SOURCE_CHARS = 4_000_000


def _esc(value) -> str:
    """V8: escape every interpolated string, text content or attribute
    value alike. `quote=True` covers the `" onload="x` attribute-breakout
    shape explicitly called out in the task brief."""
    return html.escape("" if value is None else str(value), quote=True)


def _basename(path: str) -> str:
    """Windows-first basename (§C) regardless of the host OS this tool
    happens to run on -- same rationale as report.py's `_to_file_uri`
    deliberately using `PureWindowsPath` rather than the ambient `os.path`."""
    return ntpath.basename(path) if path else ""


def _norm_loc(file: str, line: int) -> tuple[str, int]:
    """Same normalisation as `Finding.key()` (§B.2/V26): normalised full
    path, not basename -- two different files can share a basename."""
    return (os.path.normcase(os.path.normpath(file)), line)


# ---------------------------------------------------------------------------
# layout -- longest-path (rank) layering, per agent lane
# ---------------------------------------------------------------------------


def _dependency_targets(graph: Graph, node: Node) -> list[str]:
    """Every OTHER node `node` has a real scheduling dependency on, for
    LAYOUT purposes only: the union of `Requires` and `After` resolved to
    actual node names via `Graph.resolve_ref` (which already folds
    node/aggregate/agent precedence and `#tag` producer lookup, V2/R8).

    Deliberately the union of both -- unlike the two DISPLAYED edge kinds
    (`_build_edges`, which keep Requires/After visually distinct per §T13,
    since only Requires is proven dataflow, R23/V13), a node's *position*
    should reflect every real ordering constraint, tagged or not."""
    seen: set[str] = set()
    out: list[str] = []
    for token in node.requires + node.after:
        for resolved in graph.resolve_ref(token):
            if resolved in graph.nodes and resolved != node.name and resolved not in seen:
                seen.add(resolved)
                out.append(resolved)
    return out


def _compute_ranks(graph: Graph) -> dict[str, int]:
    """Longest-path rank per node: 0 for a node with no resolved
    dependencies, else 1 + max(rank(dep) for dep in dependencies). This is
    what makes "left-to-right in dependency order" and "same column, no
    path between them = parallel" (§T13) fall out of a single number.

    # ponytail: ceiling = cycle-SAFE, not cycle-optimal -- a node first
    # reached through a cyclic path is treated as rank 0 for that edge
    # (never cached as such, see `visiting` below) rather than recursed
    # into forever. A real BuildGraph dependency cycle is a serious script
    # bug no §V/§D row here claims to detect; this guard exists purely so a
    # malformed/adversarial graph can never hang the renderer. Upgrade
    # path: an SCC condensation (Tarjan) would rank cycle members exactly,
    # if a future corpus ever needs it.
    """
    deps_cache = {name: _dependency_targets(graph, node) for name, node in graph.nodes.items()}
    ranks: dict[str, int] = {}
    visiting: set[str] = set()

    def rank_of(name: str) -> int:
        if name in ranks:
            return ranks[name]
        if name in visiting:
            return 0
        visiting.add(name)
        best = 0
        for dep in deps_cache.get(name, []):
            best = max(best, rank_of(dep) + 1)
        visiting.discard(name)
        ranks[name] = best
        return best

    for name in graph.nodes:
        rank_of(name)
    return ranks



# ---------------------------------------------------------------------------
# Blueprint-style connection splines.
#
# This is Unreal's own wire formula, not an approximation of the look.
# FConnectionDrawingPolicy::ComputeSplineTangent, with the Kismet graph
# defaults:
#
#     forward  (End.X >= Start.X): H/V range 1000, H/V tangent (1.0, 0)
#     backward (End.X <  Start.X): H/V range  200, H tangent (2.0, 0),
#                                                  V tangent (1.5, 0)
#
#     ClampedTensionX = min(|Delta.X|, HorizontalDeltaRange)
#     ClampedTensionY = min(|Delta.Y|, VerticalDeltaRange)
#     Tangent = ClampedTensionX * HTangent + ClampedTensionY * VTangent
#
# Both tangent vectors are purely horizontal, which is what gives Blueprint
# wires their flat entry and exit into a pin, and why a large VERTICAL gap
# still widens the curve horizontally rather than bowing it vertically.
#
# Slate draws a Hermite spline; SVG speaks cubic Bezier. The conversion is
# exact: C1 = P0 + T0/3, C2 = P1 - T1/3. UE passes the same tangent at both
# ends of a connection, so both control points use it.
# ---------------------------------------------------------------------------

_SPLINE_FWD_RANGE = 1000.0
_SPLINE_FWD_H = 1.0
_SPLINE_FWD_V = 1.0
_SPLINE_BACK_RANGE = 200.0
_SPLINE_BACK_H = 2.0
_SPLINE_BACK_V = 1.5


def _spline_tangent(dx: float, dy: float) -> float:
    """Horizontal tangent magnitude for a connection, per UE's policy."""
    backwards = dx < 0
    rng = _SPLINE_BACK_RANGE if backwards else _SPLINE_FWD_RANGE
    h = _SPLINE_BACK_H if backwards else _SPLINE_FWD_H
    v = _SPLINE_BACK_V if backwards else _SPLINE_FWD_V
    return min(abs(dx), rng) * h + min(abs(dy), rng) * v


def _spline_path(x1: float, y1: float, x2: float, y2: float) -> str:
    """SVG `d` for a Blueprint-style wire from (x1,y1) to (x2,y2)."""
    t = _spline_tangent(x2 - x1, y2 - y1) / 3.0
    return f"M{x1:.1f},{y1:.1f} C{x1 + t:.1f},{y1:.1f} {x2 - t:.1f},{y2:.1f} {x2:.1f},{y2:.1f}"


def _node_width(name: str, has_badge: bool) -> int:
    """Box width that fits `name`, clamped to [_NODE_MIN_W, _NODE_MAX_W].

    Monospace, so length is enough (see the constants above). A node carrying
    a warn badge reserves room for it, otherwise the badge sits on top of the
    last few characters of its own node's name -- which is precisely the node
    a reader most needs to be able to read."""
    text = _NODE_PAD_X * 2 + len(name) * _NODE_CHAR_W + (_NODE_BADGE_W if has_badge else 0)
    return int(max(_NODE_MIN_W, min(_NODE_MAX_W, round(text))))


def _assign_rows(
    graph: Graph,
    lane_nodes: list[str],
    ranks: dict[str, int],
    col_x: dict[int, int],
    col_w: dict[int, int],
    widths: dict[str, int],
) -> dict[str, float]:
    """Row per node within one lane, allocated by SUBTREE rather than by
    source order.

    The old rule -- "row = index among same-rank siblings, in declaration
    order" -- packed every rank from row 0 down, so two independent branches
    of the graph interleaved: rank 1 held branch A's child at row 0 and
    branch B's child at row 1 regardless of where A and B themselves sat.
    The wires then had to cross the lane to reach their own subtree, and
    crossed whatever boxes were in the way.

    Here each node's dependents get their own rows and each subtree its own
    contiguous vertical band, so a fan-out of four lands on four rows and
    stays there. A parent is centred on the band its dependents occupy,
    which is what makes a fan read as a fan.

    Rows are FLOAT. A parent sitting at 1.5 -- halfway between two
    dependents -- is the whole point of centring, and `row * _ROW_H` does
    not care whether the multiplier is whole.

    This is a DAG, not a tree, so two things need care and get it below:
    a node reachable from several parents is placed by whichever reaches it
    first and merely read back by the rest (otherwise a diamond would be
    drawn twice), and a cyclic path is broken rather than followed forever
    -- same guard, and same reasoning, as `_compute_ranks`.

    Cost, stated plainly: a lane is now about as tall as it has leaves,
    where before it was as tall as its widest rank. That is the price of
    not routing wires through boxes, and lanes collapse.
    """
    in_lane = set(lane_nodes)
    order = {name: i for i, name in enumerate(lane_nodes)}

    # dependent lists: `children[x]` = nodes in this lane that depend on x.
    # Built from the same resolved Requires+After union the layout already
    # uses for ranking, so a node sits under whatever it actually waits for.
    children: dict[str, list[str]] = {name: [] for name in lane_nodes}
    edges: list[tuple[str, str]] = []
    for name in lane_nodes:
        for dep in _dependency_targets(graph, graph.nodes[name]):
            if dep in in_lane and dep != name and name not in children[dep]:
                children[dep].append(name)
                edges.append((dep, name))

    ranks_of: dict[str, int] = {name: ranks.get(name, 0) for name in lane_nodes}

    # Tags produced anywhere in THIS lane, case-folded like every other name
    # comparison in this tool. Built once; the sort below asks per sibling.
    lane_produced = {
        tag.lower()
        for n in lane_nodes
        for tag in (graph.nodes[n].produces | graph.nodes[n].creates)
    }
    # `resolve_ref` walks every node for each token, and Requires lists repeat
    # the same tokens across a lane constantly -- memoised so the ordering
    # below stays linear-ish rather than quadratic on a thousand-node graph.
    resolved_cache: dict[str, list[str]] = {}

    def _resolve(token: str) -> list[str]:
        if token not in resolved_cache:
            resolved_cache[token] = graph.resolve_ref(token)
        return resolved_cache[token]

    weights: dict[str, tuple[int, int, int, int, int]] = {}
    for n in lane_nodes:
        node = graph.nodes[n]
        # How far this node's furthest dependent in this lane sits, in
        # columns. NEGATED, so the longest reach sorts FIRST.
        #
        # A wire that skips columns is the one most likely to cross
        # something -- everything between its ends is in its way. Putting
        # its source at the top of the band runs it along the lane's edge,
        # where there is nothing to cross. This only ever breaks a tie
        # between nodes that are equally simple by the four counts above;
        # measured case, `BuildEditorAndTools.xml`, where `Update Version
        # Files` and `Compile UnrealEditor Win64` are both 0/0/0/0 and only
        # their reach (1 column vs 2) tells them apart.
        reach = max((ranks_of[c] - ranks_of[n] for c in children[n]), default=0)
        # (waits on IN THIS LANE, reads from THIS LANE, waits on at all,
        #  reads at all).
        #
        # In-lane first, and that ordering is the whole point. A dependency
        # or a tag read that resolves inside this same lane becomes a wire
        # drawn IN this lane, and in-lane wires are the only ones row
        # allocation can do anything about. A node with six cross-agent
        # Requires and one local one is, as far as this lane's picture is
        # concerned, a simple node -- ranking it by its global totals would
        # sink it to the bottom on account of wires drawn somewhere else.
        # The global counts stay on as tiebreaks, so two nodes that look
        # identical locally still order stably by how entangled they are
        # overall.
        local_req = sum(1 for token in node.requires if any(r in in_lane for r in _resolve(token)))
        local_con = sum(1 for tag in node.consumes if tag.lower() in lane_produced)
        weights[n] = (local_req, local_con, len(node.requires), len(node.consumes), -reach)

    def _weight(name: str) -> tuple[int, int, int, int, int]:
        """How entangled a node is, for sibling ordering."""
        return weights.get(name, (0, 0, 0, 0, 0))

    for name in children:
        # Siblings are ordered LEAST-ENTANGLED FIRST, measured inside this
        # lane before anywhere else: fewest same-lane Requires, then fewest
        # same-lane Consumes, then the global counts, then LONGEST REACH --
        # so the
        # simplest dependents sit on the top rows and the ones waiting on
        # more sink below them. Within a fan-out that puts the short, direct
        # branches where they are easy to follow and lets the tangled ones
        # spread out underneath, instead of the two interleaving.
        # Declaration order is the final tiebreak: the only stable one, and
        # it keeps the drawing in step with how the script reads.
        children[name].sort(
            key=lambda c: (_weight(c), ranks_of.get(c, 0), order.get(c, 0))
        )

    base: dict[str, float] = {}
    cursor = [0.0]
    visiting: set[str] = set()

    def place(name: str) -> float | None:
        if name in base:
            return base[name]
        if name in visiting:
            return None                      # cycle: break, do not recurse
        visiting.add(name)
        kid_rows = [r for r in (place(c) for c in children[name]) if r is not None]
        visiting.discard(name)
        if kid_rows:
            base[name] = (min(kid_rows) + max(kid_rows)) / 2.0
        else:
            base[name] = cursor[0]
            cursor[0] += 1.0
        return base[name]

    # Roots first (nothing in this lane depends on them), then anything left
    # over -- isolated nodes, cycle members.
    #
    # Roots go through the SAME least-entangled-first ordering as any other
    # sibling set. They were previously walked in plain declaration order,
    # which quietly exempted the top level from the rule: a lane's top-level
    # nodes are siblings of each other, and the first one walked claims the
    # whole downstream subtree and the top band with it, so their order
    # decides the shape of everything below.
    root_order = sorted(
        (n for n in lane_nodes if n not in {c for kids in children.values() for c in kids}),
        key=lambda n: (_weight(n), ranks_of[n], order[n]),
    )
    for name in root_order:
        place(name)
    for name in lane_nodes:
        place(name)

    by_rank: dict[int, list[str]] = {}
    for name in lane_nodes:
        by_rank.setdefault(ranks_of[name], []).append(name)

    # Corridors for wires that SKIP a rank.
    #
    # Subtree banding keeps a wire clear of its siblings' boxes, but it can
    # do nothing about an edge spanning rank 0 to rank 2: that wire crosses
    # rank 1 wherever rank 1 happens to be, and lands through whatever box
    # sits there.
    #
    # The corridor has to be where the WIRE is, which is the interpolated
    # row between the edge's endpoints -- not the target's row. Anchoring it
    # to the target was the first attempt and it is wrong in a way that
    # looks right: measured on Epic's `BuildEditorAndTools.xml`,
    # `Tag Output Files` (row 1.5) -> `Stage for UGS` (row 3.0) crosses the
    # middle rank at row 2.25, while the reservation sat at 3.0 and left
    # `Store Symbols` sitting at 2.0 directly in the wire's path.
    #
    # Interpolating needs the endpoint rows, which is what we are solving
    # for, so this iterates: obstacles from the last pass, boxes re-placed
    # from their ORIGINAL banded rows each time (never from the previous
    # pass's, or a box nudged down once keeps drifting down for ever).
    # Converges in a couple of rounds on every graph in the corpus; the cap
    # is a backstop against a shape that oscillates, not an expectation.
    def obstacles_from(rows: dict[str, float]) -> dict[int, list[tuple[float, float]]]:
        """The row BAND each rank-skipping wire occupies while it is inside
        each column it crosses.

        Sampled off the real cubic, not interpolated in rank space. A linear
        guess is tempting -- for a two-rank gap the curve's own midpoint is
        exactly the average of the endpoints -- but that midpoint is the
        midpoint in `t`, which is not where the crossed COLUMN sits: columns
        are packed to their own contents and are not evenly spaced. Measured
        on `BuildEditorAndTools.xml`, the linear guess put
        `Compile UnrealEditor Win64 -> Tag Output Files` at row 2.0 over the
        middle column while the wire was really near 1.7, so
        `Compile Tools Win64` at row 1.5 was judged clear and was not.

        Row units throughout: the lane's y offset is a constant that cancels
        when a wire is compared against a box in the same lane."""
        out: dict[int, list[tuple[float, float]]] = {}
        for dep, name in edges:
            gap = ranks_of[name] - ranks_of[dep]
            if gap <= 1:
                continue
            ax = col_x[ranks_of[dep]] + widths[dep]
            bx = col_x[ranks_of[name]]
            ay = rows[dep] * _ROW_H
            by = rows[name] * _ROW_H
            tang = _spline_tangent(bx - ax, by - ay) / 3.0
            c1x, c2x = ax + tang, bx - tang
            spans = {
                r: (col_x[r], col_x[r] + col_w[r])
                for r in range(ranks_of[dep] + 1, ranks_of[name])
            }
            lo: dict[int, float] = {}
            hi: dict[int, float] = {}
            for i in range(65):
                t = i / 64.0
                u = 1 - t
                x = u * u * u * ax + 3 * u * u * t * c1x + 3 * u * t * t * c2x + t * t * t * bx
                y = u * u * u * ay + 3 * u * u * t * ay + 3 * u * t * t * by + t * t * t * by
                row = y / _ROW_H
                for r, (x0, x1) in spans.items():
                    if x0 <= x <= x1:
                        lo[r] = min(lo.get(r, row), row)
                        hi[r] = max(hi.get(r, row), row)
            for r in spans:
                if r in lo:
                    out.setdefault(r, []).append((lo[r], hi[r]))
        return out

    def separate(obstacles: dict[int, list[tuple[float, float]]]) -> dict[str, float]:
        """Place every box at the nearest free row at or below its banded
        row, clearing the wire bands and the boxes already placed.

        Two clearances, because they guard different things: a box must not
        overlap another BOX (a full row apart), but only has to clear a WIRE
        by half a box height (`_WIRE_CLEARANCE`)."""
        out: dict[str, float] = {}
        for rank, names in by_rank.items():
            wires = list(obstacles.get(rank, ()))
            boxes: list[float] = []
            # Ties on the banded row are common -- two nodes centred over the
            # same downstream subtree land on exactly the same base row --
            # and whoever is sorted first gets the upper slot. So the tie
            # goes to the SAME least-entangled-first key used everywhere
            # else, not to declaration order; otherwise the ordering rule
            # silently stops applying at precisely the moment it decides
            # something.
            for name in sorted(names, key=lambda n: (base[n], _weight(n), order[n])):
                want = base[name]
                for _ in range(64):          # bounded: each step clears one blocker
                    push = None
                    for b in boxes:
                        if abs(want - b) < 1.0:
                            push = max(push, b + 1.0) if push is not None else b + 1.0
                    for lo, hi in wires:
                        if lo - _WIRE_CLEARANCE < want < hi + _WIRE_CLEARANCE:
                            edge = hi + _WIRE_CLEARANCE
                            push = max(push, edge) if push is not None else edge
                    if push is None:
                        break
                    want = push
                out[name] = want
                boxes.append(want)
        return out

    rows = separate({})
    for _ in range(4):
        nxt = separate(obstacles_from(rows))
        if nxt == rows:
            break
        rows = nxt

    if rows:
        top = min(rows.values())
        for name in rows:
            rows[name] -= top                # lane starts at row 0
    return rows


def _assign_positions(graph: Graph, warn_nodes: set[str]) -> tuple[list[dict], dict[str, dict], int]:
    """Lane list (agent order = `Graph.agents`' own insertion order, i.e.
    declaration order per model.build()) and a per-node {lane, col, row}
    position: col = rank (longest-path, shared across the whole graph, so
    the SAME column in different lanes lines up visually -- that alignment
    IS the "no dependency path between them -> parallel" signal §T13 asks
    to make legible); row = index among same-rank siblings within that
    SAME lane, in source order, so two nodes that happen to land on the
    same rank inside one agent stack vertically instead of colliding.

    Each node also gets a concrete `w` (its own label's width) and `x` (its
    local offset inside the lane). Columns are packed to the widest box in
    them, ACROSS ALL LANES -- column alignment between lanes is the signal
    that two nodes are at the same dependency depth and therefore run in
    parallel, so a per-lane packing would destroy the one thing the layout
    exists to show. Shipping `x`/`w` per node also means the inline script no
    longer re-derives box positions from `MARGIN_X + col * COL_W`; there is
    one arithmetic, here, and the JS reads its result."""
    ranks = _compute_ranks(graph)
    lane_names = list(graph.agents.keys())
    lanes: list[dict] = []
    node_pos: dict[str, dict] = {}

    widths = {name: _node_width(name, name in warn_nodes) for name in graph.nodes}
    col_w: dict[int, int] = {}
    for name in graph.nodes:
        col = ranks.get(name, 0)
        col_w[col] = max(col_w.get(col, _NODE_MIN_W), widths[name])
    col_x: dict[int, int] = {}
    running = _MARGIN_X
    for col in sorted(col_w):
        col_x[col] = running
        running += col_w[col] + _COL_GAP

    for lane_index, lane_name in enumerate(lane_names):
        node_names = graph.agents[lane_name]
        rows = _assign_rows(graph, node_names, ranks, col_x, col_w, widths)
        max_row = 0.0
        for name in node_names:
            rank = ranks.get(name, 0)
            row = rows.get(name, 0.0)
            node_pos[name] = {
                "lane": lane_index,
                "col": rank,
                "row": row,
                "x": col_x[rank],
                "w": widths[name],
            }
            max_row = max(max_row, row + 1)
        lanes.append(
            {
                "name": lane_name,
                "index": lane_index,
                "rows": max(max_row, 1.0),
                "node_count": len(node_names),
            }
        )
    total_width = max((running - _COL_GAP + _MARGIN_X), 400) if col_x else 400
    return lanes, node_pos, total_width


def _build_edges(graph: Graph) -> list[tuple[str, str, str]]:
    """(from_node, to_node, kind) for every DISPLAYED edge, kept separate
    from `_dependency_targets`' layout-only union: `Requires` is dataflow
    (R23/V13 -- even a bare node-name Requires carries that node's implicit
    tagged default output across the agent boundary), `After` is
    order-only (explicitly no file transfer). Deduped -- a diamond
    dependency or a repeated token would otherwise draw the same line
    twice."""
    seen: set[tuple[str, str, str]] = set()
    edges: list[tuple[str, str, str]] = []
    for name, node in graph.nodes.items():
        for tokens, kind in ((node.requires, "dataflow"), (node.after, "order")):
            for token in tokens:
                for resolved in graph.resolve_ref(token):
                    if resolved not in graph.nodes or resolved == name:
                        continue
                    key = (resolved, name, kind)
                    if key not in seen:
                        seen.add(key)
                        edges.append(key)
    return edges


