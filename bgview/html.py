def _json_script_safe(obj) -> str:
    """`json.dumps` then neutralise `<`, `>`, `&` -- a `</script` substring
    inside the JSON text would otherwise prematurely close the element
    regardless of its `type=` (the HTML parser's tag-closing scan does not
    care about JS/JSON string context). `ensure_ascii=True` (the default)
    already reduces everything else to plain ASCII, so only these three
    characters need handling. `\\uXXXX` round-trips through `JSON.parse`
    exactly like the literal character would."""
    text = json.dumps(obj, ensure_ascii=True, separators=(",", ":"))
    return text.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


