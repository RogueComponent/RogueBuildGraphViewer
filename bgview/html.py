def _d12_verdicts(findings: list[Finding]) -> dict[tuple[str, int], str]:
    """(file, line) -> "unsat" | "taut", read straight off D12's own
    finding messages (detectors._d12: "is unsatisfiable" / "is
    tautological"). A raw_if with no entry here was classified
    "contingent" or "unknown" by algebra.classify -- D12 deliberately
    emits nothing for either (V10/V14: never guess through an opaque or
    genuinely-both-ways guard) -- so this module has no way to tell those
    two apart without recomputing algebra.classify itself, which the task
    brief explicitly says not to do. Shown to the user as one honest label
    covering both, rather than a fabricated guess."""
    verdicts: dict[tuple[str, int], str] = {}
    for f in findings:
        if f.detector != "D12":
            continue
        loc = _norm_loc(f.file, f.line)
        msg = f.message.lower()
        if "unsatisfiable" in msg:
            verdicts[loc] = "unsat"
        elif "tautological" in msg:
            verdicts[loc] = "taut"
    return verdicts


def _collect_conditions(ev: EvalResult, verdicts: dict[tuple[str, int], str]):
    """Every `raw_if` in the script, split into node-attached (surfaced in
    that node's inspector card) and node-less (surfaced on the enclosing
    agent's lane header tooltip -- e.g. the target file's own
    `SubmissionDependencies` accumulator guard at line 65, a top-level
    `<Property>` sitting directly under `<Agent>`, outside any `<Node>`)."""
    by_node: dict[str, list[dict]] = {}
    by_agent: dict[str, list[dict]] = {}
    seen: set[tuple[str, str, int]] = set()
    for r in ev.resolved:
        if not r.raw_if:
            continue
        key = (r.node or "", r.elem.file, r.elem.line)
        if key in seen:
            continue
        seen.add(key)
        loc = _norm_loc(r.elem.file, r.elem.line)
        entry = {"text": r.raw_if, "line": r.elem.line, "cls": verdicts.get(loc)}
        if r.node:
            by_node.setdefault(r.node, []).append(entry)
        elif r.agent:
            by_agent.setdefault(r.agent, []).append(entry)
    return by_node, by_agent


