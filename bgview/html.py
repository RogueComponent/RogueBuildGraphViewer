"""bgview.html -- self-contained HTML report (T13).

This is the deliverable the user actually asked for: a graphical way to see
a BuildGraph script's tag dataflow, condition paths, and agent/parallelism
structure, with the findings from `bgview.detectors`/`bgview.evaluator` as
the entry point into it (findings-first; the graph is evidence, not
decoration -- §C).

Rendering only. This module never re-derives a finding, a tag-dataflow
edge, or a condition verdict -- everything it draws comes straight out of
`Graph`/`EvalResult`/`list[Finding]` as already computed by model.py /
evaluator.py / detectors.py. The one thing it DOES compute itself is purely
cosmetic: a longest-path (x = dependency rank) layout so nodes lay out
left-to-right in dependency order within each agent's swimlane, per §T13's
"simple layered (longest-path) layout" instruction -- this has no effect on
any finding, it only decides where a box is drawn.

Security posture (V8, trust boundary -- a BuildGraph script is a file from
another team's repo, not trusted input):

  * Every attacker-influenced string (node/agent/tag name, Log message,
    file path, option value, finding message, condition text) that lands in
    the STATIC HTML/SVG markup goes through `_esc` (`html.escape(...,
    quote=True)`) -- text content AND attribute values alike.
  * Element `id`/`class` tokens are never derived from graph data -- they
    are synthetic, index-based (`n0`, `l3`, `edge`-by-array-index, `f7`),
    generated by this module. This sidesteps an entire class of
    id/selector-injection bugs and keeps `document.getElementById` lookups
    trivially safe.
  * Graph-derived data reaches JS through exactly one channel: a
    `<script type="application/json">` block, parsed with `JSON.parse` --
    never string-interpolated into executable JS source. Because a
    `</script` substring inside that JSON would prematurely close the tag
    regardless of `type=`, the JSON text additionally has `<`, `>`, `&`
    escaped to `\\uXXXX` before being embedded (the standard mitigation --
    same one Flask/Django's `tojson` filters apply).
  * The inline `<script>` at the bottom never uses `innerHTML` /
    `outerHTML` / `insertAdjacentHTML` / `document.write` with any
    graph-derived string. Text is written via `.textContent` (which never
    interprets its argument as markup, so no separate escaping is needed
    there) or `document.createElement` + `.textContent`. Numeric/geometry
    values are written via `setAttribute`/`style`. All event wiring is
    `addEventListener`; there are no inline `on*=` attributes anywhere in
    the generated document.

Self-containment (V17/§C): the whole document -- HTML, CSS, JS, and data --
is one string written to one file. No `<link>`, no `<script src=...>`, no
web fonts, no images, no CDN. It must render correctly opened directly via
`file://`, which is also why layout is computed once server-side (Python)
for the initial paint and mirrored arithmetically in the inline script for
interactive re-layout on lane collapse/expand -- both are plain local
computation, nothing fetched.
"""

