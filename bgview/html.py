def _render_svg(
    graph: Graph,
    lanes: list[dict],
    node_pos: dict[str, dict],
    edges: list[tuple[str, str, str]],
    node_id_by_name: dict[str, str],
    lane_id_by_index: list[str],
    warn_nodes: set[str],
    agent_conditions: dict[str, list[dict]],
    collapsed_default: bool,
    total_width: int,
) -> tuple[str, int, int]:
    lane_y: dict[int, int] = {}
    y = _MARGIN_TOP
    for lane in lanes:
        lane_y[lane["index"]] = y
        y += _LANE_HEADER_H + lane["rows"] * _ROW_H + _LANE_PAD
    total_height = max(y, 120)

    parts: list[str] = []
    parts.append(
        f'<svg id="graph-svg" xmlns="http://www.w3.org/2000/svg" width="{total_width}" height="{total_height}" '
        f'viewBox="0 0 {total_width} {total_height}" role="group" aria-label="BuildGraph dependency graph">'
    )
    # One clipPath per node width actually in use, not one per node: boxes
    # share widths constantly (every node in a column that hit the same
    # clamp, every short name at the floor), and a defs block with one entry
    # per node would be dead weight in a thousand-node graph.
    clip_widths = sorted({pos["w"] for pos in node_pos.values()})
    clips = "".join(
        f'<clipPath id="node-clip-{w}"><rect x="0" y="0" width="{w - _NODE_PAD_X}" height="{_NODE_H}"/></clipPath>'
        for w in clip_widths
    )
    parts.append(
        f"""<defs>{clips}
  <marker id="arrow-dataflow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">
    <path d="M0,0 L10,5 L0,10 z" class="arrow-dataflow-fill"/>
  </marker>
  <marker id="arrow-order" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">
    <path d="M0,0 L10,5 L0,10 z" class="arrow-order-fill"/>
  </marker>
</defs>"""
    )


    for lane in lanes:
        lane_id = lane_id_by_index[lane["index"]]
        agent_name = lane["name"] or "(unnamed agent)"
        extra_title = ""
        conds = agent_conditions.get(lane["name"], [])
        if conds:
            lines = "\n".join(f"- {c['text']} [{c['cls'] or 'not statically classified'}] (line {c['line']})" for c in conds)
            extra_title = f"\n\n{len(conds)} node-less condition(s):\n{lines}"
        parts.append(
            f'<g class="lane" id="lane-{lane_id}" data-lane-index="{lane["index"]}" '
            f'transform="translate(0,{lane_y[lane["index"]]})">'
        )
        parts.append(
            f'<g class="lane-header" id="lanehdr-{lane_id}" data-lane-id="{lane_id}" tabindex="0" role="button" '
            f'aria-expanded="{"false" if collapsed_default else "true"}">'
            f'<rect class="lane-header-bg" x="0" y="0" width="{total_width}" height="{_LANE_HEADER_H}"/>'
            f'<path class="lane-chevron" d="M10,{_LANE_HEADER_H / 2 - 5:.0f} l7,5 l-7,5 z"/>'
            f'<text class="lane-title" x="26" y="{_LANE_HEADER_H / 2 + 5:.0f}">'
            f'{_esc(agent_name)} · {lane["node_count"]} node(s)</text>'
            f"<title>{_esc(agent_name + extra_title)}</title>"
            f"</g>"
        )
        parts.append(f'<g class="lane-body" id="lanebody-{lane_id}">')
        for name in graph.agents[lane["name"]]:
            node = graph.nodes[name]
            pos = node_pos[name]
            node_id = node_id_by_name[name]
            local_x = pos["x"]
            local_y = _LANE_HEADER_H + pos["row"] * _ROW_H
            node_w = pos["w"]
            warn_cls = " has-warning" if name in warn_nodes else ""
            parts.append(
                f'<g class="node{warn_cls}" id="node-{node_id}" data-node-id="{node_id}" '
                f'transform="translate({local_x},{local_y})" tabindex="0" role="button" '
                f'aria-label="Node {_esc(name)} in agent {_esc(agent_name)}">'
                f'<rect class="node-box" width="{node_w}" height="{_NODE_H}" rx="6"/>'
                f'<text class="node-label" x="{_NODE_PAD_X}" y="{_NODE_H / 2 + 4:.0f}" '
                f'clip-path="url(#node-clip-{node_w})">{_esc(name)}</text>'
                f"<title>{_esc(_node_title(node))}</title>"
            )
            if name in warn_nodes:
                parts.append(
                    f'<circle class="warn-badge" cx="{node_w - 7}" cy="7" r="7"/>'
                    f'<text class="warn-badge-text" x="{node_w - 7}" y="10.5" text-anchor="middle">!</text>'
                )
            parts.append("</g>")
        parts.append("</g></g>")

    # Last child of the <svg>, and INSIDE it: emitted after every lane so it
    # paints on top of the lane headers, but before </svg> -- put after the
    # closing tag it is not part of the drawing at all and renders as nothing.
    # Edges are emitted AFTER the lanes on purpose. SVG has no z-index --
    # painting order IS document order -- so with the edge layer first every
    # lane-header-bg rect painted straight over any wire crossing it, and a
    # cross-lane connection disappeared behind the header of the lane it
    # passed through: precisely the connections most worth seeing. Emitting
    # last puts the wires on top. Positions are fully absolute (they cross
    # lane boundaries), mirrored by relayout() in the inline script.
    # since they may cross lane boundaries (see module docstring / JS
    # relayout()'s mirrored formula).
    parts.append('<g id="edge-layer">')
    for i, (from_name, to_name, kind) in enumerate(edges):
        a, b = node_pos[from_name], node_pos[to_name]
        ax = a["x"] + a["w"]          # leaves the producer's right edge
        ay = lane_y[a["lane"]] + _LANE_HEADER_H + a["row"] * _ROW_H + _NODE_H / 2
        bx = b["x"]                   # arrives at the consumer's left edge
        by = lane_y[b["lane"]] + _LANE_HEADER_H + b["row"] * _ROW_H + _NODE_H / 2
        marker = "arrow-dataflow" if kind == "dataflow" else "arrow-order"
        parts.append(
            f'<path id="edge-{i}" class="edge edge-{kind}" data-from="{node_id_by_name[from_name]}" '
            f'data-to="{node_id_by_name[to_name]}" d="{_spline_path(ax, ay, bx, by)}" '
            f'marker-end="url(#{marker})"><title>{_esc(from_name)} -&gt; {_esc(to_name)} ({kind})</title></path>'
        )
    parts.append("</g>")

    parts.append("</svg>")

    return "".join(parts), total_width, total_height


