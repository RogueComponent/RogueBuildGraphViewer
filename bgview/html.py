def _node_by_loc(graph: Graph) -> dict[tuple[str, int], str]:
    return {_norm_loc(n.file, n.line): name for name, n in graph.nodes.items()}


def _agent_by_loc(ev: EvalResult) -> dict[tuple[str, int], str]:
    """Agent declaration sites, read directly off `ev.resolved` (never
    recomputed/inferred) -- `Graph.agents` itself carries no line/file for
    the `<Agent>` element, only its node list, so this is the one place
    that information is available at all."""
    out: dict[tuple[str, int], str] = {}
    for r in ev.resolved:
        if r.elem.tag == "Agent":
            out[_norm_loc(r.elem.file, r.elem.line)] = r.attrs.get("Name", "")
    return out


def _finding_target(
    f: Finding,
    graph: Graph,
    node_by_loc: dict[tuple[str, int], str],
    agent_by_loc: dict[tuple[str, int], str],
) -> tuple[str, str] | None:
    """Best-effort ("node", name) / ("agent", name) mapping for the
    findings-panel click -> select+scroll+highlight behaviour (§T13).
    Falls through, in order, from the most direct signal to the least:
    the finding's own `.node`; its `.tag`'s producer node; an exact
    (file, line) match against a Node's own declaration site (covers a
    finding anchored on the `<Node>` element itself, e.g. D10 on a
    trailing ';' in `Node/@Requires`); an exact (file, line) match against
    an `<Agent>` declaration site (D15, `Agent/@Type`). A finding with
    none of these (e.g. D8 on a top-level `<Property>` outside any node)
    has no graph target -- returns None rather than guessing one."""
    if f.node and f.node in graph.nodes:
        return ("node", f.node)
    if f.tag:
        producers = graph.producers_of(f.tag)
        if producers:
            return ("node", producers[0])
    loc = _norm_loc(f.file, f.line)
    if loc in node_by_loc:
        return ("node", node_by_loc[loc])
    if loc in agent_by_loc:
        return ("agent", agent_by_loc[loc])
    return None


